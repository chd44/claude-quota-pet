import Foundation
@testable import QuotaPetCore

func lifecycleChecks() {
    check(LaunchModeTransition.shouldDisablePrevious(enabling: true, succeeded: true, active: true, needsApproval: false), "Active newly selected mode replaces previous mode")
    check(!LaunchModeTransition.shouldDisablePrevious(enabling: true, succeeded: false, active: true, needsApproval: false), "Failed mode change preserves previous mode")
    check(!LaunchModeTransition.shouldDisablePrevious(enabling: true, succeeded: true, active: false, needsApproval: true), "Pending approval preserves previous mode")
    check(!LaunchModeTransition.shouldDisablePrevious(enabling: false, succeeded: true, active: false, needsApproval: false), "Disabling mode permits both modes off")
    let isolated = TransientDefaults()
    isolated.set("demo", forKey: "language")
    check(isolated.string(forKey: "language") == "demo", "Demo settings retain edits in memory")
    isolated.set(true, forKey: "boolEdit")
    check(isolated.bool(forKey: "boolEdit"), "Demo toggles use in-memory values")
    check(isolated.persistentDomain(forName: isolated.domainName) == nil, "Demo setting edits never persist")
    isolated.register(defaults: ["demoFlag": true])
    check(isolated.bool(forKey: "demoFlag"), "Demo settings honor registered defaults")
    check(!TransientDefaults().bool(forKey: "demoFlag"), "Each demo settings instance starts independently")
    check(DesktopActivation.isCLI(URL(string: "quotapet://cli")!), "CLI launch URL promotes session")
    check(!DesktopActivation.isCLI(URL(string: "quotapet://other")!), "Unrelated launch URL cannot promote session")
    check(!DesktopActivation.isCLI(URL(string: "https://cli")!), "Remote URL cannot promote session")
    var session = DesktopRunSession(automatic: true)
    check(session.shouldExit(claudeRunning: false, codexRunning: false), "Automatic desktop session exits after last desktop closes")
    check(!session.shouldExit(claudeRunning: false, codexRunning: true), "Other desktop keeps automatic session alive")
    session.keepRunning()
    check(!session.shouldExit(claudeRunning: false, codexRunning: false), "CLI or manual activation retains app after desktop closes")
    check(!DesktopRunSession(automatic: false).shouldExit(claudeRunning: false, codexRunning: false), "Manual and CLI-only users retain app")
    var gate = DesktopLaunchGate()
    check(!gate.shouldLaunch(enabled: false, paused: false, runningIDs: ["com.openai.codex"], appRunning: false), "Disabled launcher never opens app")
    check(!gate.shouldLaunch(enabled: true, paused: false, runningIDs: ["com.apple.Terminal"], appRunning: false), "CLI terminal does not trigger desktop launch")
    check(gate.shouldLaunch(enabled: true, paused: false, runningIDs: ["com.openai.codex"], appRunning: false), "Desktop app opens fully stopped QuotaPet")
    check(!gate.shouldLaunch(enabled: true, paused: false, runningIDs: ["com.openai.codex"], appRunning: false), "Same running desktop cannot repeatedly relaunch")
    check(!gate.shouldLaunch(enabled: true, paused: false, runningIDs: [], appRunning: false), "Desktop termination rearms without opening")
    check(!gate.shouldLaunch(enabled: true, paused: true, runningIDs: ["com.anthropic.claudefordesktop"], appRunning: false), "Explicit quit suppresses auto launch")
    _ = gate.shouldLaunch(enabled: true, paused: false, runningIDs: [], appRunning: false)
    check(!gate.shouldLaunch(enabled: true, paused: false, runningIDs: ["com.openai.codex"], appRunning: true), "Already running app is not opened again")
}
